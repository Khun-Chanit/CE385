// ข้อมูลบัญชีที่ถูกต้องในระบบ
const VALID_USERNAME = "admin";
const VALID_PASSWORD = "ce385pass";

// ฟังก์ชันตรวจสอบสิทธิ์การเข้าสู่ระบบ
function login(inputUser, inputPass, role, isActive, age) {
  // ลำดับที่ 1: ตรวจ username หรือ password ก่อนเป็นอันดับแรก
  if (inputUser !== VALID_USERNAME || inputPass !== VALID_PASSWORD) {
    return "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง"; // เทียบกับ 401
  }

  // ลำดับที่ 2: ตรวจว่าบัญชีถูกระงับหรือไม่
  if (isActive === false) {
    return "บัญชีนี้ถูกระงับการใช้งาน"; // เทียบกับ 403
  }

  // ลำดับที่ 3: ตรวจอายุ
  if (age < 18) {
    return "อายุไม่ถึงเกณฑ์";
  }

  // ลำดับที่ 4-5: ผ่านทุกข้อแล้ว ตรวจ role เพื่อกำหนดสิทธิ์
  if (role === "อาจารย์") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ผู้ดูแล)"; // เทียบกับ 200
  } else if (role === "นักศึกษา") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ทั่วไป)"; // เทียบกับ 200
  }

  // กรณี role ไม่ตรงกับที่ระบบรู้จัก (ป้องกันไว้เผื่อข้อมูลผิดปกติ)
  return "บทบาทผู้ใช้ไม่ถูกต้อง";
}

// ===== ส่วนที่ 2: ทดสอบอย่างน้อย 6 กรณี =====

// 1. สำเร็จ (อาจารย์)
console.log(`ทดสอบ 1 (อาจารย์ผ่านทุกข้อ): ${login("admin", "ce385pass", "อาจารย์", true, 35)}`);

// 2. สำเร็จ (นักศึกษา)
console.log(`ทดสอบ 2 (นักศึกษาผ่านทุกข้อ): ${login("admin", "ce385pass", "นักศึกษา", true, 20)}`);

// 3. รหัสผ่านผิด
console.log(`ทดสอบ 3 (รหัสผ่านผิด): ${login("admin", "wrongpass", "นักศึกษา", true, 20)}`);

// 4. ชื่อผู้ใช้ผิด
console.log(`ทดสอบ 4 (ชื่อผู้ใช้ผิด): ${login("wronguser", "ce385pass", "นักศึกษา", true, 20)}`);

// 5. บัญชีถูกระงับ
console.log(`ทดสอบ 5 (บัญชีถูกระงับ): ${login("admin", "ce385pass", "นักศึกษา", false, 20)}`);

// 6. อายุไม่ถึงเกณฑ์
console.log(`ทดสอบ 6 (อายุไม่ถึงเกณฑ์): ${login("admin", "ce385pass", "นักศึกษา", true, 15)}`);

// ===== ตอบคำถามท้ายข้อ =====

// คำถามที่ 1: ทำไมต้องตรวจ username/password ก่อน ตรวจ role
// เพราะ role เป็นข้อมูลที่ถูกส่งเข้ามาพร้อมกับคำขอ (input) เช่นเดียวกับ username/password 
// แต่ role นี้ยังไม่ได้รับการยืนยันว่าเป็นของบัญชีที่แท้จริงหรือไม่ ถ้าไม่ตรวจ
// username/password ก่อน ก็เท่ากับปล่อยให้ใครก็ได้ที่ไม่มีบัญชีจริง ส่งค่า role
// เป็น "อาจารย์" เข้ามาตรงๆ แล้วได้สิทธิ์ผู้ดูแลไปเลยโดยไม่ต้องพิสูจน์ตัวตนก่อน
// จึงต้องยืนยันตัวตน (authentication) ให้ผ่านก่อน แล้วค่อยตรวจสิทธิ์ (authorization)

// คำถามที่ 2: ถ้าย้ายการตรวจ "อายุไม่ถึงเกณฑ์" ขึ้นไปเป็นข้อแรก จะเกิดปัญหาอะไร
// จะเกิดปัญหาด้านความปลอดภัยและการรั่วไหลของข้อมูล (information leakage)
// เพราะระบบจะบอกผลลัพธ์เรื่องอายุให้กับคนที่ยังพิสูจน์ตัวตนไม่ผ่านด้วยซ้ำ
// เท่ากับเป็นการ "บอกอะไร" กับคนที่ยังไม่ได้พิสูจน์ตัวตน (เช่น แฮกเกอร์ที่เดา
// username/password ผิด) ว่าบัญชีนี้มีอยู่จริงและมีข้อมูลอายุอยู่ในระบบ
// ซึ่งอาจถูกนำไปใช้เดาหรือโจมตีระบบต่อได้ ดังนั้นข้อมูลที่ยังไม่ผ่านการยืนยัน
// ตัวตนไม่ควรถูกนำมาตรวจหรือเปิดเผยผลลัพธ์ใดๆ ทั้งสิ้น