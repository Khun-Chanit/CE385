// ฟังก์ชันแปลงคะแนนเป็นเกรด
function toGrade(score) {
  // ต้องตรวจสอบข้อมูลนำเข้าก่อนตัดเกรดเสมอ (สำคัญมากสำหรับงาน Backend)
  // ถ้าคะแนนต่ำกว่า 0 หรือมากกว่า 100 ถือว่าข้อมูลไม่ถูกต้อง ไม่ต้องตัดเกรดให้
  if (score < 0 || score > 100) {
    return "คะแนนไม่ถูกต้อง ต้องอยู่ระหว่าง 0-100";
  }

  // ต้องเรียงเงื่อนไขจากคะแนนมากไปน้อยเสมอ เพราะ if...else if จะหยุดตรวจ
  // ทันทีที่เจอเงื่อนไขแรกที่เป็นจริง ถ้าเรียงจากน้อยไปมาก
  // เช่น ถ้าเช็ค >= 0 ก่อน คะแนน 80 ก็จะเข้าเงื่อนไขนั้นทันทีและได้เกรด F ผิดพลาด
  // ดังนั้นต้องเช็คช่วงคะแนนสูงสุดก่อน แล้วค่อยไล่ลงมาช่วงต่ำสุด
  if (score >= 80) {
    return "A";
  } else if (score >= 75) {
    return "B+";
  } else if (score >= 70) {
    return "B";
  } else if (score >= 65) {
    return "C+";
  } else if (score >= 60) {
    return "C";
  } else if (score >= 55) {
    return "D+";
  } else if (score >= 50) {
    return "D";
  } else {
    return "F";
  }
}

// ส่วนที่ 3: ทดสอบให้ครบทุกค่าโดยใช้ array และ for...of
const testScores = [95, 80, 79, 75, 70, 65, 60, 55, 50, 49, 0, -5, 120];

for (const score of testScores) {
  console.log(`คะแนน ${score} → เกรด ${toGrade(score)}`);
}