import { getAllStudents } from "./student-data.mjs";
import { toGrade, isPassing, summarize } from "./student-service.mjs";

const students = getAllStudents();

// ตารางรายชื่อพร้อมเกรด
const report = students.map((s) => ({
  ชื่อ: s.name,
  สาขา: s.major,
  คะแนน: s.score,
  เกรด: toGrade(s.score),
  สถานะ: isPassing(s.score) ? "ผ่าน" : "ไม่ผ่าน",
}));

console.table(report);

// สรุปท้ายตาราง
const summary = summarize(students);
console.log("สรุปผลรวม:", summary);

